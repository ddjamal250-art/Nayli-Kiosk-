class MasterCatalogItem {
  final String barcode;
  final String name;
  final String category;
  final double defaultPrice;
  final double defaultCost;
  final double wholesalePrice;
  final String? imageUrl;
  final bool isTobacco;
  final double cartonPrice;
  final double cartonCostPrice;
  final double wholesaleCartonPrice;
  final double wholesalePackPrice;
  final double singlePiecePrice;
  final int piecesPerPack;
  final int packsPerCarton;
  final String unitType;

  const MasterCatalogItem({
    required this.barcode,
    required this.name,
    required this.category,
    this.defaultPrice = 0.0,
    this.defaultCost = 0.0,
    this.wholesalePrice = 0.0,
    this.imageUrl,
    this.isTobacco = false,
    this.cartonPrice = 0.0,
    this.cartonCostPrice = 0.0,
    this.wholesaleCartonPrice = 0.0,
    this.wholesalePackPrice = 0.0,
    this.singlePiecePrice = 0.0,
    this.piecesPerPack = 20,
    this.packsPerCarton = 10,
    this.unitType = 'piece',
  });

  String get categoryIcon {
    if (category.contains('تبغ') || category.contains('سجائر') || isTobacco) return '🚬';
    if (category.contains('شمة')) return '🌿';
    if (category.contains('معسل') || category.contains('شيشة')) return '💨';
    if (category.contains('ولاع')) return '🔥';
    if (category.contains('ورق لف') || category.contains('فلاتر')) return '📜';
    if (category.contains('متر') || unitType == 'meter') return '📏';
    if (category.contains('عطر') || unitType == 'ml') return '🧴';
    if (category.contains('ألبان') || category.contains('حليب') || category.contains('ياغورت')) return '🥛';
    if (category.contains('مشروب') || category.contains('عصير') || category.contains('ماء')) return '🥤';
    if (category.contains('تنظيف') || category.contains('صابون')) return '🧼';
    if (category.contains('حلويات') || category.contains('بسكويت') || category.contains('شوكولا')) return '🍫';
    if (category.contains('معلبات') || category.contains('تونة') || category.contains('طماطم')) return '🥫';
    if (category.contains('ميزان') || category.contains('بقوليات') || category.contains('عدس')) return '⚖️';
    if (category.contains('خبز') || category.contains('مخبوزات')) return '🥖';
    if (category.contains('بيض')) return '🥚';
    return '📦';
  }
}

